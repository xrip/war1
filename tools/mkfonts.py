#!/usr/bin/env python3
# mkfonts.py — war1's font atlases (8x-upscaled PNGs) to src/render/fonts.h:
# native-size glyph pixels, 0 clear, 1 black, 2 white (tinted when drawn).
# Copyright (c) 2026 Mikhail Matveev <xtreme@rh1.tech>
# SPDX-License-Identifier: Zlib
import sys
from PIL import Image

out = ["// Generated by tools/mkfonts.py from assets/war1_font_*.png.",
       "#pragma once", ""]
for n, path in enumerate(sys.argv[1:], 1):
    im = Image.open(path).convert("RGBA")
    w, h = im.size[0] // 8, im.size[1] // 8
    px = im.load()
    vals = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x * 8, y * 8]
            vals.append(0 if a < 128 else (1 if r < 128 else 2))
    out.append(f"#define WAR_FONT{n}_W {w}")
    out.append(f"#define WAR_FONT{n}_H {h}")
    out.append(f"static const unsigned char war_font{n}[{w * h}] = {{")
    for i in range(0, len(vals), 64):
        out.append("    " + ",".join(str(v) for v in vals[i:i + 64]) + ",")
    out.append("};")
    out.append("")
sys.stdout.write("\n".join(out))
